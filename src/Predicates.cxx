int orient3d_sos(const Vec3* p1[4], const unsigned rank1[4])
{
  auto sign = [](double x) { return x > 0. ? 1 : -1; };
  auto orient1d = [](double a, double b) { return a > b ? 1 : a < b ? -1 : 0; };

  const double pa[3] = { p1[0]->x, p1[0]->y, p1[0]->z }, pb[3] = { p1[1]->x, p1[1]->y, p1[1]->z };
  const double pc[3] = { p1[2]->x, p1[2]->y, p1[2]->z }, pd[3] = { p1[3]->x, p1[3]->y, p1[3]->z };
  double o = orient3d(pa, pb, pc, pd);
  if (o != 0.)
    return sign(o);

  // sortp: a bubble sort by rank, counting the swaps.
  const Vec3* p[4] = { p1[0], p1[1], p1[2], p1[3] };
  unsigned r[4] = { rank1[0], rank1[1], rank1[2], rank1[3] };
  int s = 1;
  for (int i = 0; i < 3; i++)
    for (int j = 0; j < 3 - i; j++)
      if (r[j + 1] < r[j])
      {
        std::swap(r[j], r[j + 1]);
        std::swap(p[j], p[j + 1]);
        s = - s;
      }

  auto o2 = [](double ax, double ay, double bx, double by, double cx, double cy) {
    const double a[2] = { ax, ay }, b[2] = { bx, by }, c[2] = { cx, cy };
    return orient2d(a, b, c);
  };

  // epsilon^1/8
  if ((o = o2(p[1]->x, p[1]->y, p[2]->x, p[2]->y, p[3]->x, p[3]->y)) != 0.) return sign(o) * s;
  // epsilon^1/4
  if ((o = o2(p[1]->x, p[1]->z, p[2]->x, p[2]->z, p[3]->x, p[3]->z)) != 0.) return - sign(o) * s;
  // epsilon^1/2
  if ((o = o2(p[1]->y, p[1]->z, p[2]->y, p[2]->z, p[3]->y, p[3]->z)) != 0.) return sign(o) * s;
  // epsilon
  if ((o = o2(p[0]->x, p[0]->y, p[2]->x, p[2]->y, p[3]->x, p[3]->y)) != 0.) return - sign(o) * s;
  // epsilon^5/4
  if (int k = orient1d(p[2]->x, p[3]->x)) return sign(k) * s;
  // epsilon^3/2
  if (int k = orient1d(p[2]->y, p[3]->y)) return - sign(k) * s;
  // epsilon^2
  if ((o = o2(p[0]->x, p[0]->z, p[2]->x, p[2]->z, p[3]->x, p[3]->z)) != 0.) return sign(o) * s;
  // epsilon^5/2
  if (int k = orient1d(p[2]->z, p[3]->z)) return sign(k) * s;
  // epsilon^4
  if ((o = o2(p[0]->y, p[0]->z, p[2]->y, p[2]->z, p[3]->y, p[3]->z)) != 0.) return - sign(o) * s;
  // epsilon^8
  if ((o = o2(p[0]->x, p[0]->y, p[1]->x, p[1]->y, p[3]->x, p[3]->y)) != 0.) return sign(o) * s;
  // epsilon^33/4
  if (int k = orient1d(p[1]->x, p[3]->x)) return - sign(k) * s;
  // epsilon^17/2
  if (int k = orient1d(p[1]->y, p[3]->y)) return sign(k) * s;
  // epsilon^10
  if (int k = orient1d(p[0]->x, p[3]->x)) return sign(k) * s;
  // epsilon^21/2
  return s;
}

